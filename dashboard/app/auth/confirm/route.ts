import type { EmailOtpType } from "@supabase/supabase-js";
import { redirect } from "next/navigation";
import type { NextRequest } from "next/server";

import { createClient } from "@/lib/supabase/server";

// Target of the magic link: {{ .SiteURL }}/auth/confirm?token_hash={{ .TokenHash }}&type=email&next=/fleet
export async function GET(request: NextRequest) {
  const params = request.nextUrl.searchParams;
  const tokenHash = params.get("token_hash");
  const type = params.get("type") as EmailOtpType | null;
  const next = params.get("next") ?? "/fleet";
  const safeNext = next.startsWith("/") && !next.startsWith("//") ? next : "/fleet";

  if (tokenHash && type) {
    const supabase = await createClient();
    const { error } = await supabase.auth.verifyOtp({ type, token_hash: tokenHash });
    if (!error) redirect(safeNext);
  }
  redirect("/login?error=link");
}
